"""Inventory app-owned XAML and generated native controls; no dependencies or app-data access."""
from collections import Counter
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "Scriblucent"
X = "{http://schemas.microsoft.com/winfx/2006/xaml}"
WIDGETS = set("Button MenuItem ComboBox ComboBoxItem CheckBox ScrollViewer TextBox Separator ContextMenu Thumb ToggleButton RadioButton RepeatButton Slider ListBox ListBoxItem ToolTip Calendar CalendarItem CalendarButton CalendarDayButton DatePicker DatePickerTextBox RichTextBox Expander ScrollBar TabControl TabItem ProgressBar ListView TreeView DataGrid GroupBox PasswordBox GridSplitter".split())
REFINED = {
    "MainWindow.xaml", "NoteEditorWindow.xaml", "NoteEditorTabsWindow.xaml", "StyleNodeDialog.xaml",
    "ColorPickerDialog.xaml", "ItemInfoDialog.xaml", "FlashcardCombineWindow.xaml", "QuizLibraryWindow.xaml",
    "FlashcardStatisticsWindow.xaml", "FlashcardsPreviewWindow.xaml", "QuizPreviewWindow.xaml",
    "NoteSchedulePanel.xaml", "FlashcardsDashboardPage.xaml", "MindMapPreviewWindow.xaml",
    "FlashcardStudyHistoryWindow.xaml", "QuizAttemptHistoryWindow.xaml", "EditHistoryWindow.xaml",
}


def inventory():
    documents, total, styles, generated = [], Counter(), [], []
    for path in sorted(APP.rglob("*.xaml")):
        if {"bin", "obj"} & set(path.parts):
            continue
        root = ET.parse(path).getroot()
        widgets = Counter()
        for node in root.iter():
            tag = node.tag.split("}")[-1]
            if tag in WIDGETS:
                widgets[tag] += 1
            if tag == "Style":
                template = any(child.tag.endswith("Setter") and child.attrib.get("Property") == "Template" for child in node)
                styles.append({"file": path.relative_to(ROOT).as_posix(), "key": node.attrib.get(X + "Key"),
                               "target": node.attrib.get("TargetType"), "basedOn": node.attrib.get("BasedOn"), "ownsTemplate": template})
        total.update(widgets)
        kind = root.tag.split("}")[-1]
        if kind in {"Window", "UserControl"}:
            documents.append({"file": path.relative_to(ROOT).as_posix(), "kind": kind,
                              "decision": "Refine" if path.name in REFINED else "Keep",
                              "widgets": dict(widgets)})
    for path in sorted(APP.rglob("*.cs")):
        if {"bin", "obj"} & set(path.parts):
            continue
        text = path.read_text(encoding="utf-8-sig")
        for match in re.finditer(r"\bnew\s+(?:System\.Windows\.Controls\.)?(\w+)\s*(?:\(|\{)", text):
            if match[1] in WIDGETS:
                generated.append({"file": path.relative_to(ROOT).as_posix(), "line": text.count("\n", 0, match.start()) + 1,
                                  "type": match[1]})
    return {"screens": documents, "widgetCounts": dict(sorted(total.items())), "styles": styles, "generatedControls": generated}


if __name__ == "__main__":
    data = inventory()
    output = ROOT / "artifacts" / "motion" / "premium-ui"
    output.mkdir(parents=True, exist_ok=True)
    (output / "source-inventory.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    lines = ["# App-owned UI inventory", "", "Generated by `python tools/audit-ui.py`.", "",
             "This is source coverage, not a claim that every possible runtime state has been photographed. Shared templates affect retained screens too.", "",
             "| Native widget | XAML declarations |", "| --- | ---: |"]
    lines.extend(f"| {name} | {count} |" for name, count in data["widgetCounts"].items())
    lines += ["", "## Screen decisions", "", "Keep: preserve the established app template/material/motion language; use the shared typography, focus and viewport repairs where inherited.",
              "Refine: composition, density, optical alignment or native template ownership changes across the premium and integrated-workspace passes. Domain workflows remain intact.", "",
              "| Screen | Decision | Native widget declarations |", "| --- | --- | ---: |"]
    lines.extend(f"| {item['file']} | {item['decision']} | {sum(item['widgets'].values())} |" for item in data["screens"])
    lines += ["", "## Generated controls", "", "These sites were checked against shared implicit styles and explicit local styles. Exact color/font samples and document content retain their distinct roles.",
              "", "| Source | Type |", "| --- | --- |"]
    lines.extend(f"| {item['file']}:{item['line']} | {item['type']} |" for item in data["generatedControls"])
    lines += ["", "## Intentional native internals", "",
              "ContentControl and ItemsControl default templates only present content; they have no widget chrome. TextBoxView, ScrollContentPresenter, document glyphs and vendor vector icon renderers remain native engines.",
              "Invisible slider RepeatButtons retain native track commands. Visible thumbs, scrollbars, selectors, menus, fields and calendar controls use app templates.",
              "Native operating-system file/print dialogs and caption frames remain platform surfaces. No unused widget styles were added.", ""]
    (output / "inventory.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Inventoried {len(data['screens'])} screens, {sum(data['widgetCounts'].values())} native widget declarations, {len(data['styles'])} styles and {len(data['generatedControls'])} generated-control sites.")
